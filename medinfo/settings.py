from urllib.parse import parse_qs, urlparse

_raw_db_url = os.environ.get("DATABASE_NEON", "").strip() or os.environ.get("DATABASE_URL", "").strip()

if _raw_db_url:
    _parsed = urlparse(_raw_db_url)
    _query = parse_qs(_parsed.query)
    _options = {}
    if "sslmode" in _query:
        _options["sslmode"] = _query["sslmode"][0]
    else:
        _options["sslmode"] = "require"

    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.postgresql",
            "NAME": _parsed.path.lstrip("/"),
            "USER": _parsed.username or "",
            "PASSWORD": _parsed.password or "",
            "HOST": _parsed.hostname or "",
            "PORT": str(_parsed.port or 5432),
            "CONN_MAX_AGE": 60,
            "OPTIONS": _options,
        }
    }
